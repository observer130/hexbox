/**
 * 取一个字母的字形（轮廓 + 度量；只认 A~Z，小写与大写等价，其他字符返回 `null`）。
 *
 * 没有字形时**明确返回 null**：调用方（离线预览）据此回退到内置单线字形/提示框，
 * 绝不静默漏画。
 */
export function tierLetterGlyph(ch: string): TierLetterGlyph | null {
  const key = ch.trim().toUpperCase().slice(0, 1)
  const contours = TIER_LETTER_OUTLINES[key]
  const metrics = tierLetterEmMetrics(key)
  return contours && metrics ? { ...metrics, contours } : null
}

